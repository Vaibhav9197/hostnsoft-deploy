/**
 * scale-to-zero-apps.js — THE allowlist.
 *
 * Hardcoded and frozen on purpose. An allowlist read from the environment
 * or a config file could be widened by accident, or by a deploy that
 * shipped the wrong file; adding an app here is a code change that has to
 * be reviewed and deployed. That friction is the point — see Step 3 of
 * docs/scale-to-zero-gated-plan.md.
 *
 * ONE list, because two processes depend on it and they must agree:
 * idle-report.js may only STOP an app named here, activator.js may only
 * WAKE one. An app stoppable but not wakeable is an app taken offline
 * permanently; wakeable but not stoppable is merely dead code. They were
 * separate constants in separate files, which is a divergence waiting to
 * happen for the worse of those two outcomes.
 *
 * A THIRD copy still exists: the per-app routers in /opt/traefik/dynamic.yml,
 * generated by server-setup.sh, without which no request for a stopped app
 * ever reaches the activator. That one cannot read this file — dynamic.yml
 * is written before the repo is pulled — so for now it is kept in step by
 * hand. Step 7 replaces it with routers generated from this list.
 *
 * Before adding an app, check all three:
 *   - its running spec has DATA_DIR=/data (idle-report enforces this, but
 *     an unmigrated app needs downtime to fix, so choose accordingly)
 *   - it has no custom domain (the routers only cover <app>.<suffix>, so a
 *     stopped app would still 404 on a custom domain)
 *   - its owner has agreed to the cold-start tradeoff
 */

// Step 6: the throwaway test app plus two real, non-critical apps whose
// owners have agreed. Both were already on DATA_DIR=/data, so neither
// needed a migration with user-visible downtime first.
//
// `focus` was chosen for this list and then removed: it serves a custom
// domain, focus.walkover.uk. The routers that hand a stopped app's
// traffic to the activator only cover <app>.<APPS_DOMAIN_SUFFIX>, so
// while stopped it would have 404'd on someone's real domain — no wake,
// no warning, no entry in any log that says why. It is a good candidate
// once Step 7 generates routers per hostname rather than per app.
// socket-ux is deliberately different from the other two, in two ways
// worth knowing before reading any failure it produces:
//
//   - It is still on DATA_DIR=/alloc/data, not the host bind mount.
//     Allowed because its allocation directory is EMPTY, so a stop
//     destroys nothing; idle-report re-checks that before every stop and
//     refuses if anything has appeared since. Safe, but it is the first
//     unmigrated app on this list.
//   - It is the first app expected to use WebSockets, which means it is
//     the first real exercise of activator.js's upgrade proxying. That
//     path only became necessary when allowlisted apps moved to being
//     routed through the activator permanently, and it has never run
//     against a real client. If something here breaks, look there first.
